/// Points per generated curve: the most stops one `linear()` string carries.
const CURVE_POINTS: usize = motion::MAX_STOPS;

/// A spring has settled once it is within 1 percent (10 per mille) of its target.
const SETTLE_TOLERANCE: i32 = 10;

/// One indium preset fitted to its settle time.
struct Fitted {
    name: &'static str,
    settle_ms: u32,
    points: Vec<i32>,
}

/// The three springs of section 4.2, in the order they are written.
fn fitted_presets() -> Vec<Fitted> {
    [("firm", FIRM), ("live", LIVE), ("heavy", HEAVY)]
        .into_iter()
        .map(|(name, p)| fit(name, p))
        .collect()
}

/// Sample `p` over its settle time (not its full length) so the curve lasts exactly as long as its token.
fn fit(name: &'static str, p: Preset) -> Fitted {
    // One sample per millisecond, so index i is the position at i ms.
    let track = motion::sample(p, p.duration_ms as usize + 1);
    let settled_from = track
        .iter()
        .rposition(|v| (v - 1000).abs() > SETTLE_TOLERANCE)
        .map_or(0, |i| i + 1);
    let settle_ms = u32::try_from(settled_from).unwrap_or(p.duration_ms).max(1);
    let fitted = Preset {
        duration_ms: settle_ms,
        ..p
    };
    Fitted {
        name,
        settle_ms,
        points: settled_points(fitted),
    }
}

/// Curve points for `p`, with the last one pinned to the target: the curve must end where it is drawn to.
fn settled_points(p: Preset) -> Vec<i32> {
    let mut points = motion::sample(p, CURVE_POINTS);
    if let Some(last) = points.last_mut() {
        *last = 1000;
    }
    points
}

/// CSS for the spring tokens of section 4.2, generated from `indium::motion`.
///
/// Durations are always set. The `linear()` curves sit under `@supports`, so other browsers keep
/// `--ease-out` from `tokens.css`. Under reduced motion every spring lasts 0.01 ms.
pub fn motion_css() -> String {
    let fits = fitted_presets();
    let mut out = String::from(
        "/* neon-tokens */\n/* Generated by neon::webkit::motion_css from indium::motion. Do not edit: run cargo test -p neon --test motion -- --ignored regenerate_motion_files */\n:root {\n",
    );
    for f in &fits {
        out.push_str(&format!("  --spring-{}-t: {}ms;\n", f.name, f.settle_ms));
    }
    out.push_str("}\n@supports (animation-timing-function: linear(0, 1)) {\n  :root {\n");
    for f in &fits {
        out.push_str(&format!(
            "    --spring-{}: {};\n",
            f.name,
            motion::css_linear(&f.points)
        ));
    }
    out.push_str("  }\n}\n");
    out.push_str("@media (prefers-reduced-motion: reduce) {\n  :root {\n");
    for f in &fits {
        out.push_str(&format!("    --spring-{}-t: 0.01ms;\n", f.name));
    }
    out.push_str("  }\n}\n:root[data-motion=\"reduce\"] {\n");
    for f in &fits {
        out.push_str(&format!("  --spring-{}-t: 0.01ms;\n", f.name));
    }
    out.push_str("}\n");
    out
}

/// JavaScript that defines `MOTION_TABLE`: per spring its settle time `ms` and 32 `points` in per mille.
pub fn motion_table_js() -> String {
    let mut out = String::from(
        "/* neon-tokens */\n/* Generated by neon::webkit::motion_table_js from indium::motion. Do not edit: run cargo test -p neon --test motion -- --ignored regenerate_motion_files */\nvar MOTION_TABLE = {",
    );
    let entries: Vec<String> = fitted_presets()
        .iter()
        .map(|f| {
            let points: Vec<String> = f.points.iter().map(i32::to_string).collect();
            format!(
                "\"{}\": {{\"ms\": {}, \"points\": [{}]}}",
                f.name,
                f.settle_ms,
                points.join(", ")
            )
        })
        .collect();
    out.push_str(&entries.join(", "));
    out.push_str("};\n");
    out
}

const SW_TEMPLATE: &str = r#"// Service worker written by neon::webkit::sw_js. It opens only its own cache.
var PREFIX = __PREFIX__;
var CACHE = PREFIX + "-" + __HASH__;
var FILES = __FILES__;
self.addEventListener("install", function (ev) {
  ev.waitUntil(caches.open(CACHE).then(function (cache) {
    return cache.addAll(FILES);
  }).then(function () {
    return self.skipWaiting();
  }));
});
self.addEventListener("activate", function (ev) {
  ev.waitUntil(caches.keys().then(function (keys) {
    return Promise.all(keys.filter(function (k) {
      return k.indexOf(PREFIX + "-") === 0 && k !== CACHE;
    }).map(function (k) {
      return caches.delete(k);
    }));
  }).then(function () {
    return self.clients.claim();
  }));
});
self.addEventListener("fetch", function (ev) {
  if (ev.request.method !== "GET") {
    return;
  }
  if (new URL(ev.request.url).origin !== self.location.origin) {
    return;
  }
  ev.respondWith(caches.open(CACHE).then(function (cache) {
    return cache.match(ev.request).then(function (hit) {
      return hit || fetch(ev.request);
    });
  }));
});
"#;

/// Run cargo for `args` in the repo root with its own target dir; the error carries cargo's stderr.
pub fn run_cargo(cargo: &str, root: &Path, target_dir: &Path, args: &[&str]) -> Result<(), String> {
    let output = Command::new(cargo)
        .current_dir(root)
        .env("CARGO_TARGET_DIR", target_dir)
        .args(args)
        .output()
        .map_err(|e| format!("failed to spawn cargo ({}): {e}", args.join(" ")))?;
    if !output.status.success() {
        let stderr = String::from_utf8_lossy(&output.stderr);
        return Err(format!(
            "cargo {} failed ({}):\n{stderr}",
            args.join(" "),
            output.status
        ));
    }
    Ok(())
}

/// FNV-1a 64-bit hash of all parts as 16 hex digits. Names caches; not a security hash.
pub fn content_hash(parts: &[&[u8]]) -> String {
    const PRIME: u64 = 0x0100_0000_01b3;
    let mut h: u64 = 0xcbf2_9ce4_8422_2325;
    for part in parts {
        for &b in *part {
            h ^= u64::from(b);
            h = h.wrapping_mul(PRIME);
        }
        // Separator byte, so that ["ab", "c"] and ["a", "bc"] hash differently.
        h ^= 0xff;
        h = h.wrapping_mul(PRIME);
    }
    format!("{h:016x}")
}

/// Service worker source. It uses only the cache `<prefix>-<hash>`, precaches `files` (paths
/// relative to the worker) and answers cache first, then the network.
pub fn sw_js(prefix: &str, hash: &str, files: &[&str]) -> String {
    let list = files
        .iter()
        .map(|f| js_str(f))
        .collect::<Vec<_>>()
        .join(", ");
    SW_TEMPLATE
        .replace("__PREFIX__", &js_str(prefix))
        .replace("__HASH__", &js_str(hash))
        .replace("__FILES__", &format!("[{list}]"))
}

/// A JavaScript string literal, escaped so that no input can end the literal or the script.
fn js_str(s: &str) -> String {
    const BACKSLASH: char = '\u{5c}';
    let mut out = String::from("\"");
    for ch in s.chars() {
        match ch {
            '"' => {
                out.push(BACKSLASH);
                out.push('"');
            }
            '\\' => {
                out.push(BACKSLASH);
                out.push(BACKSLASH);
            }
            '<' => out.push_str(&format!("{BACKSLASH}u003c")),
            c if c.is_control() => out.push_str(&format!("{BACKSLASH}u{:04x}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// Marker on the first line of a token or generated file, the only files where a bare duration may appear.
pub const TOKEN_MARKER: &str = "/* neon-tokens */";

/// Problems found in one kit file (empty when it passes): external URLs, `will-change`, `setInterval(`,
/// transitions and keyframes that move anything but opacity and transform, and bare durations
/// (every duration is a token, except in files that start with `TOKEN_MARKER`).
pub fn lint(text: &str) -> Vec<String> {
    let mut problems = Vec::new();
    for scheme in ["http://", "https://"] {
        if text.contains(scheme) {
            problems.push(format!(
                "external URL `{scheme}`: load only files served next to the page"
            ));
        }
    }
    if text.contains("will-change") {
        problems.push("`will-change`: animate only opacity and transform".to_string());
    }
    if text.contains("setInterval(") {
        problems.push("`setInterval(`: drive timing from the kit's frame loop".to_string());
    }
    problems.extend(transition_problems(text));
    problems.extend(keyframe_problems(text));
    if !text.starts_with(TOKEN_MARKER) {
        problems.extend(duration_problems(text));
    }
    problems
}

/// `lint` plus the rule for page code: `requestAnimationFrame(` belongs to the kit (`Motion`).
pub fn lint_page(text: &str) -> Vec<String> {
    let mut problems = lint(text);
    if text.contains("requestAnimationFrame(") {
        problems.push(
            "`requestAnimationFrame(` outside the kit: use Motion.tween or Motion.canvas"
                .to_string(),
        );
    }
    problems
}

/// Transitions may name only opacity and transform.
fn transition_problems(text: &str) -> Vec<String> {
    let lower = text.to_ascii_lowercase();
    let mut problems = Vec::new();
    for (at, _) in lower.match_indices("transition") {
        let rest = lower.get(at + "transition".len()..).unwrap_or("");
        let rest = rest.strip_prefix("-property").unwrap_or(rest).trim_start();
        let value = match rest.strip_prefix(':') {
            Some(value) => value,
            None => continue,
        };
        let decl = value.split([';', '}', '\n']).next().unwrap_or("");
        for item in decl.split(',') {
            let prop = item.split_whitespace().next().unwrap_or("");
            if !matches!(prop, "" | "none" | "opacity" | "transform") {
                problems.push(format!(
                    "transition on `{prop}`: animate only opacity and transform"
                ));
            }
        }
    }
    problems
}

/// Keyframes may set only opacity and transform.
fn keyframe_problems(text: &str) -> Vec<String> {
    let mut problems = Vec::new();
    for (at, _) in text.match_indices("@keyframes") {
        let body = text.get(at..).unwrap_or("");
        let Some(open) = body.find('{') else {
            continue;
        };
        let mut depth = 0usize;
        let mut end = body.len();
        for (i, c) in body[open..].char_indices() {
            match c {
                '{' => depth += 1,
                '}' => {
                    depth = depth.saturating_sub(1);
                    if depth == 0 {
                        end = open + i + 1;
                        break;
                    }
                }
                _ => {}
            }
        }
        let block = body.get(open..end).unwrap_or("");
        for piece in block.split(['{', '}', ';']) {
            if let Some((prop, _)) = piece.split_once(':') {
                let prop = prop.trim();
                if !prop.is_empty() && prop != "opacity" && prop != "transform" {
                    problems.push(format!(
                        "keyframes on `{prop}`: animate only opacity and transform"
                    ));
                }
            }
        }
    }
    problems
}

/// A number directly followed by `ms` or `s` (a duration literal), outside a longer word.
fn duration_problems(text: &str) -> Vec<String> {
    let chars: Vec<char> = text.chars().collect();
    let mut problems = Vec::new();
    let mut i = 0;
    while i < chars.len() {
        let prev = if i == 0 { ' ' } else { chars[i - 1] };
        let starts_number =
            chars[i].is_ascii_digit() && !(prev.is_alphanumeric() || matches!(prev, '_' | '-'));
        if !starts_number {
            i += 1;
            continue;
        }
        let mut j = i;
        while j < chars.len() && (chars[j].is_ascii_digit() || chars[j] == '.') {
            j += 1;
        }
        let suffix = if chars.get(j..j + 2) == Some(&['m', 's']) {
            2
        } else if chars.get(j) == Some(&'s') {
            1
        } else {
            0
        };
        let after = chars.get(j + suffix).copied().unwrap_or(' ');
        if suffix > 0 && !(after.is_alphanumeric() || after == '_') {
            let literal: String = chars[i..j + suffix].iter().collect();
            problems.push(format!(
                "bare duration `{literal}`: use a token from tokens.css"
            ));
        }
        i = j;
    }
    problems
}

#[cfg(test)]
mod tests {
    use super::{fitted_presets, motion_css, motion_table_js, SETTLE_TOLERANCE};

    #[test]
    fn springs_settle_within_their_section_4_2_token() {
        let limits = [("firm", 280), ("live", 450), ("heavy", 700)];
        for (f, (name, settle)) in fitted_presets().iter().zip(limits) {
            assert_eq!(f.name, name);
            assert!(f.settle_ms <= settle, "{name} settles at {}ms", f.settle_ms);
            let end = f.points.last().copied().unwrap_or(0);
            assert!(
                (end - 1000).abs() <= SETTLE_TOLERANCE,
                "{name} ends at {end}"
            );
        }
    }

    #[test]
    fn only_live_overshoots_by_4_to_8_percent() {
        let peaks: Vec<i32> = fitted_presets()
            .iter()
            .map(|f| f.points.iter().copied().max().unwrap_or(0) - 1000)
            .collect();
        assert!(peaks[0] <= 5, "firm overshoots by {}", peaks[0]);
        assert!((40..=80).contains(&peaks[1]), "live overshoot {}", peaks[1]);
        assert!(peaks[2] <= 5, "heavy overshoots by {}", peaks[2]);
    }

    #[test]
    fn generated_text_is_stable_and_names_all_springs() {
        assert_eq!(motion_css(), motion_css());
        let js = motion_table_js();
        assert_eq!(js, motion_table_js());
        for name in ["firm", "live", "heavy"] {
            assert!(js.contains(&format!("\"{name}\": {{\"ms\": ")), "{name}");
        }
    }
}
