//! Built-in 8x16 monospace bitmap font for ASCII 0x20..=0x7E and replacement box.

#[cfg(test)]
mod tests;

/// Width of each font glyph cell in pixels.
pub const GLYPH_W: u32 = 8;

/// Height of each font glyph cell in pixels.
pub const GLYPH_H: u32 = 16;

/// 16 rows of 8 bits (bit 7 = leftmost pixel) for the glyph drawn for `ch`.
///
/// ASCII `0x20..=0x7E` have their own glyphs; every other char gets the replacement glyph
/// (a hollow box), which differs from all ASCII glyphs.
pub fn glyph(ch: char) -> [u8; 16] {
    let code = ch as u32;
    if (0x20..=0x7E).contains(&code) {
        FONT[(code - 0x20) as usize]
    } else {
        REPLACEMENT
    }
}

